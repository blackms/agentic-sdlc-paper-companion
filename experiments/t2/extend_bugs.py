def main():
    existing = yaml.safe_load((ROOT / "bugs.yaml").read_text())
    existing_ids = {b["id"] for b in existing["bugs"]}
    bugs_full = list(existing["bugs"])
    added = 0
    skipped = []
    for nb in NEW_BUGS:
        if nb["id"] in existing_ids:
            continue
        # validate substitution actually changes
        if nb["sub_old"] not in REF:
            skipped.append((nb["id"], "sub_old not in REF"))
            continue
        bugged_test = REF.replace(nb["sub_old"], nb["sub_new"], 1)
        if bugged_test == REF:
            skipped.append((nb["id"], "no change after sub"))
            continue
        bugs_full.append(nb)
        added += 1

    out = {"bugs": bugs_full}
    (ROOT / "bugs_extended.yaml").write_text(yaml.safe_dump(out, sort_keys=False, allow_unicode=True))
    print(f"Added {added} new bugs. Total: {len(bugs_full)}.")
    if skipped:
        print(f"Skipped {len(skipped)}:")
        for bid, reason in skipped:
            print(f"  {bid}: {reason}")
    print(f"Saved: {ROOT / 'bugs_extended.yaml'}")


if __name__ == "__main__":
    main()
